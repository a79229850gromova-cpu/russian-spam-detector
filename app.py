# -*- coding: utf-8 -*-

import streamlit as st
import joblib


# ============================================================
# НАСТРОЙКИ СТРАНИЦЫ
# ============================================================

st.set_page_config(
    page_title="Определение спама",
    page_icon="📩",
    layout="centered"
)


# ============================================================
# ЗАГРУЗКА МОДЕЛИ
# ============================================================

model = joblib.load("spam_model.joblib")
vectorizer = joblib.load("tfidf_vectorizer.joblib")


# ============================================================
# ЗАГОЛОВОК
# ============================================================

st.title("📩 Определение спама")

st.write(
    "Введите текст сообщения, и обученная модель "
    "определит, является ли оно спамом."
)

st.markdown("---")


# ============================================================
# ПОЛЕ ДЛЯ ВВОДА
# ============================================================

st.subheader("Введите сообщение")

message = st.text_area(
    "",
    placeholder=(
        "Например: "
        "Поздравляем! Вы выиграли 1 000 000 рублей! "
        "Перейдите по ссылке для получения приза."
    ),
    height=160
)


# ============================================================
# КНОПКА
# ============================================================

check_button = st.button(
    "🔍 Проверить сообщение",
    use_container_width=True
)


# ============================================================
# ПРОВЕРКА СООБЩЕНИЯ
# ============================================================

if check_button:

    if not message.strip():

        st.warning("⚠️ Сначала введите сообщение.")

    else:

        # Преобразуем текст в признаки TF-IDF
        message_vector = vectorizer.transform([message])

        # Получаем класс
        prediction = model.predict(message_vector)[0]

        # Получаем вероятности
        probabilities = model.predict_proba(message_vector)[0]


        # ====================================================
        # ЕСЛИ СПАМ
        # ====================================================

        if prediction == 1:

            confidence = probabilities[1]

            st.error(
                "🚨 Это сообщение похоже на СПАМ"
            )

            st.metric(
                "Уверенность модели",
                f"{confidence * 100:.1f}%"
            )

            st.progress(
                float(confidence)
            )


        # ====================================================
        # ЕСЛИ НЕ СПАМ
        # ====================================================

        else:

            confidence = probabilities[0]

            st.success(
                "✅ Это сообщение похоже на НЕ СПАМ"
            )

            st.metric(
                "Уверенность модели",
                f"{confidence * 100:.1f}%"
            )

            st.progress(
                float(confidence)
            )


# ============================================================
# ИНФОРМАЦИЯ О МОДЕЛИ
# ============================================================

st.markdown("---")

st.subheader("О модели")

st.write(
    """
**Метод:** TF-IDF + Logistic Regression

**Обучающая выборка:** 500 000 сообщений

**Разделение данных:** 80% обучение / 20% тестирование

**Учет дисбаланса классов:** `class_weight="balanced"`

**Accuracy:** 98,85%

**Recall для класса «спам»:** 96%

**F1-score для класса «спам»:** 93%
"""
)

st.caption(
    "Модель обучена на русскоязычных сообщениях "
    "с разметкой «спам / не спам»."
)